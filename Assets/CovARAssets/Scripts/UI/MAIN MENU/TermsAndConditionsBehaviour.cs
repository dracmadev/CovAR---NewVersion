using UnityEngine;
using UnityEngine.UI;

public class TermsAndConditionsBehaviour : MonoBehaviour
{
    [Header("TERMS & CONDITIONS BEHAVIOUR")]
    [SerializeField] private ScrollRect _TermsAndConditionsScrollRect;
    [SerializeField] private Button _AcceptButton;
    void Start()
    {
        
    }

    // Update is called once per frame
    void Update()
    {
        OnCheckIfUserHaveReadTermsAndConditions();
    }

    ////////////////////////////////////////////////////////////////// INIT ////////////////////////////////////////////////////////////////////////////////////////


    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    ////////////////////////////////////////////////////////////////// BEHAVIOUR //////////////////////////////////////////////////////////////////////////////////

    void OnCheckIfUserHaveReadTermsAndConditions()
    {
        if (_TermsAndConditionsScrollRect.verticalNormalizedPosition <= 0.0f)
        {
            _AcceptButton.interactable = true;
        }
        else
        {
            _AcceptButton.interactable = false;
        }
    }


    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
}
